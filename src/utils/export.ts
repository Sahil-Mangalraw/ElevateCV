import { AnalysisResult } from '../types';

/**
 * Formats the entire analysis result into a clean, professional Markdown report.
 */
export function generateMarkdownReport(analysis: AnalysisResult): string {
  const dateFormatted = new Date(analysis.timestamp).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  return `# ElevateCV AI — Resume & Job Match Analysis Report
**Target Role:** ${analysis.jobTitle || 'Target Position'}
**Date of Evaluation:** ${dateFormatted}
**Overall Alignment Score:** ${analysis.overallScore}/100

---

## 1. Executive Summary & Scoring Breakdown
${analysis.scoreBreakdown.explanation}

- **Skills Match:** ${analysis.scoreBreakdown.skillsMatchScore}/100 (40% weight)
- **Experience Evidence:** ${analysis.scoreBreakdown.experienceMatchScore}/100 (30% weight)
- **Education Alignment:** ${analysis.scoreBreakdown.educationMatchScore}/100 (15% weight)
- **ATS Formatting & Clarity:** ${analysis.scoreBreakdown.atsFormattingScore}/100 (15% weight)

*Disclaimer: This score reflects objective content alignment against the provided job posting. It is not an automated hiring decision or a guarantee of recruitment success.*

---

## 2. Demonstrated Skills (${analysis.matchedSkills.length})
${analysis.matchedSkills
  .map(
    (s) =>
      `- **${s.name}** (${s.category}): ${s.contextInResume}`
  )
  .join('\n')}

---

## 3. Missing or Undeveloped Competencies (${analysis.missingSkills.length})
${analysis.missingSkills
  .map(
    (s) =>
      `- **${s.name}** [${s.importance.toUpperCase()}]: ${s.whyNeeded}`
  )
  .join('\n')}

---

## 4. Key Strengths
${analysis.strengths.map((s, idx) => `${idx + 1}. ${s}`).join('\n')}

---

## 5. Areas for Improvement
${analysis.areasForImprovement.map((s, idx) => `${idx + 1}. ${s}`).join('\n')}

---

## 6. Top 5 Actionable Recommendations
${analysis.actionableRecommendations
  .map(
    (r, idx) =>
      `### ${idx + 1}. ${r.title}
- **Action:** ${r.action}
- **Impact:** ${r.impact}
${r.exampleSnippet ? `- **Example:** \`${r.exampleSnippet}\`` : ''}`
  )
  .join('\n\n')}

---

## 7. Recommended Bullet Point Improvements
${analysis.bulletPointImprovements
  .map(
    (b, idx) =>
      `### Example ${idx + 1} (${b.styleApplied})
- **Original:** "${b.originalBullet}"
- **Critique:** ${b.critique}
- **Suggested Rewrite:** "${b.improvedBullet}"`
  )
  .join('\n\n')}

---

## 8. ATS Readability & Formatting Observations (Score: ${analysis.atsReadability.score}/100)
**Detected Sections:** ${analysis.atsReadability.detectedSections.join(', ')}

**Observations:**
${analysis.atsReadability.observations.map((o) => `- ${o}`).join('\n')}

**Formatting Risks:**
${analysis.atsReadability.formattingRisks.map((r) => `- ${r}`).join('\n')}

**Recommendations:**
${analysis.atsReadability.recommendations.map((r) => `- ${r}`).join('\n')}

---

## 9. 4-Week Actionable Learning Roadmap
${analysis.learningRoadmap
  .map(
    (m) =>
      `### ${m.milestone} (${m.timeframe})
- **Focus Skills:** ${m.focusSkills.join(', ')}
- **Action Step:** ${m.suggestedAction}
- **Resource / Project:** ${m.suggestedResourceOrProject}`
  )
  .join('\n\n')}

---
*Report generated by ElevateCV AI. No private credentials or resume texts are stored externally.*
`;
}

/**
 * Downloads a text/markdown file directly in browser.
 */
export function downloadFile(content: string, filename: string, mimeType: string = 'text/markdown'): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

/**
 * Copies formatted text to clipboard with user feedback callback.
 */
export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    } else {
      const textArea = document.createElement('textarea');
      textArea.value = text;
      textArea.style.position = 'fixed';
      textArea.style.left = '-999999px';
      document.body.appendChild(textArea);
      textArea.focus();
      textArea.select();
      const successful = document.execCommand('copy');
      document.body.removeChild(textArea);
      return successful;
    }
  } catch (err) {
    console.error('Failed to copy to clipboard', err);
    return false;
  }
}
